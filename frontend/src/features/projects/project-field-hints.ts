import type { components } from '@/api/schema';

export const projectNameHint =
  'Удобное вам название в списке проектов. Например, «СиАОД — лаба 3». Тема работы указывается отдельно.';
export function templateFieldHint(field: components['schemas']['TemplateField']): string {
  const known: Record<string, string> = {
    report_title:
      'Официальная тема из задания. Например, «Исследование алгоритмов сортировки». Она используется в документе.',
    lab_title:
      'Официальная тема из задания. Например, «Исследование алгоритмов сортировки». Она используется в документе.',
    lab_number: 'Номер лабораторной работы из задания. Например, 3.',
    variant: `Номер или буква варианта из задания преподавателя. ${field.type === 'select' ? 'Выберите свой вариант из списка.' : field.type === 'int' ? 'Например, 7.' : 'Например, 7 или Б.'}`,
    comment: 'Дополнительные пояснения к работе. Можно написать в несколько строк.',
    teacher: 'Фамилия и инициалы преподавателя в том виде, который указан в требованиях к работе.',
    work_type: 'Вид работы из задания. Например, «Лабораторная работа» или «Практическая работа».',
  };
  const fallback = {
    string: 'Введите значение для этого поля по заданию преподавателя.',
    int: 'Введите целое число из задания, без дробной части.',
    text: 'Введите текст для этого поля по заданию. Можно писать в несколько строк.',
    select: 'Выберите подходящее значение из списка по своему заданию.',
  };
  return `${known[field.key] ?? fallback[field.type]} ${field.required ? 'Обязательное поле.' : 'Необязательное поле.'}`;
}
